#!/usr/bin/env bash
# test.sh — run the unit tests.
#
# The host does not necessarily have the SDL2 development packages
# installed, so the libraries fetched by scripts/sysroot.sh are put on
# the link path instead.
#
# Usage:
#   ./scripts/test.sh
#   ARCH=aarch64 ./scripts/test.sh

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

: "${SYSROOT:=$TARGET_DIR/$ARCH-libs}"

LIBDIR="$SYSROOT/usr/lib/$MULTIARCH"
RT_DIR="$SYSROOT/usr/lib/$MULTIARCH-runtime"

if [[ ! -d "$LIBDIR" ]]; then
    die "No libraries at $LIBDIR — run: ARCH=$ARCH ./scripts/sysroot.sh"
fi

export PKG_CONFIG_SYSROOT_DIR="$SYSROOT"
export PKG_CONFIG_PATH="$LIBDIR/pkgconfig:$SYSROOT/usr/share/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
export C_INCLUDE_PATH="$SYSROOT/usr/include:$SYSROOT/usr/$MULTIARCH/include${C_INCLUDE_PATH:+:$C_INCLUDE_PATH}"

# The library search paths have to come before the `-lSDL2` that
# sdl2-sys emits: GNU ld resolves `-lfoo` at the point where it sees it.
# Cargo appends `-C link-arg=` values at the very end of the link line,
# so the paths are injected through a linker wrapper instead.
#
# The wrapper only adds the search paths; it leaves the rest of the
# arguments alone, because the same driver is also used to link the
# build scripts of the dependencies.
WRAPPER="$TARGET_DIR/linker-$ARCH-test.sh"
mkdir -p "$TARGET_DIR"
cat > "$WRAPPER" <<WRAPPER_EOF
#!/usr/bin/env bash
# Generated by scripts/test.sh — do not edit.
exec "\${LINKER:-cc}" \
    -L$RT_DIR \
    -L$LIBDIR \
    "\$@"
WRAPPER_EOF
chmod +x "$WRAPPER"

TARGET_UPPER="$(echo "$TARGET" | tr '[:lower:]-' '[:upper:]_')"
export "CARGO_TARGET_${TARGET_UPPER}_LINKER=$WRAPPER"

info "Running the tests..."
cargo test "$@"
